#!/usr/bin/env python3
"""Downscale logos/ into small inline data URIs -> assets/logos.js (run after changing logos)."""
import base64, io, json, os
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = {'openai': 'openai&chatgpt.png', 'claude': 'claude-color.png', 'gemini': 'gemini-color.png',
         'grok': 'grok.png', 'deepseek': 'deepseek-color.png', 'alibaba': 'alibaba-color.png',
         'kimi': 'kimi-color.png', 'anthropic': 'anthropic.png', 'google': 'google-color.png',
         'moonshot': 'moonshot.png'}
S = 96
out = {}
for key, name in FILES.items():
    src = Image.open(os.path.join(ROOT, 'logos', name)).convert('RGBA')
    if key == 'kimi':  # white glyph: put it on its black app-icon tile
        big = Image.new('RGBA', (4 * S, 4 * S), (0, 0, 0, 0))
        ImageDraw.Draw(big).rounded_rectangle([0, 0, 4 * S - 1, 4 * S - 1], radius=int(S * .9), fill=(0, 0, 0, 255))
        im = big.resize((S, S), Image.LANCZOS)
        inner = src.resize((int(S * .7), int(S * .7)), Image.LANCZOS)
        im.alpha_composite(inner, (int(S * .15), int(S * .15)))
    else:
        im = src.resize((S, S), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, 'PNG', optimize=True)
    out[key] = 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()
with open(os.path.join(ROOT, 'assets', 'logos.js'), 'w') as f:
    f.write('/* generated by tools/build_logos.py */\nwindow.BENCHROT_LOGOS=' + json.dumps(out, separators=(',', ':')) + ';\n')
print('wrote assets/logos.js', sum(len(v) for v in out.values()), 'bytes of data URIs')
